export function hasLlmKey(): boolean {
  return !!(process.env.ANTHROPIC_API_KEY || process.env.AI_GATEWAY_API_KEY);
}

export function hasFfmpeg(): boolean {
  const r = spawnSync("ffmpeg", ["-version"], { encoding: "utf8" });
  return r.status === 0;
}

export function hasFfprobe(): boolean {
  const r = spawnSync("ffprobe", ["-version"], { encoding: "utf8" });
  return r.status === 0;
}

export function demoChecks(): DemoCheck[] {
  const ffmpeg = hasFfmpeg() && hasFfprobe();
  const llm = hasLlmKey();
  const voice = !!config.elevenlabs.apiKey;
  const pexels = !!config.pexels.apiKey;
  return [
    {
      name: "ffmpeg + ffprobe",
      ok: ffmpeg,
      required: true,
      detail: ffmpeg
        ? "present"
        : "required to assemble a Short — install ffmpeg and retry",
    },
    {
      name: "Script LLM",
      ok: llm,
      required: false,
      detail: llm
        ? "present (fresh script)"
        : "ANTHROPIC_API_KEY missing — demo uses a canned script",
    },
    {
      name: "ElevenLabs",
      ok: voice,
      required: false,
      detail: voice
        ? "present (voiced audio)"
        : "ELEVENLABS_API_KEY missing — demo uses silent stub audio + captions",
    },
    {
      name: "Pexels",
      ok: pexels,
      required: false,
      detail: pexels
        ? "present (stock B-roll)"
        : "PEXELS_API_KEY missing — demo uses generated title-card clips",
    },
    {
      name: "YouTube OAuth",
      ok: true,
      required: false,
      detail: "not required for --demo (no upload)",
    },
  ];
}

/**
 * Demo needs ffmpeg to assemble. Missing API keys degrade (canned script,
 * silent audio, title-card clips) instead of crashing — but doctor-style
 * copy still tells you exactly what a *real* voiced stock Short requires.
 */
export function assertDemoReady(): void {
  const checks = demoChecks();
  const ffmpeg = checks.find((c) => c.name.startsWith("ffmpeg"))!;
  if (!ffmpeg.ok) {
    throw new Error(
      demoFailure(
        "ffmpeg/ffprobe is missing, so the pipeline cannot assemble a Short.",
        checks,
      ),
    );
  }
}

export function printDemoReadiness(heading = "Demo readiness (`npm run make -- --demo`)"): void {
  const checks = demoChecks();
  console.log(`\n${heading}:`);
  for (const c of checks) {
    const mark = c.ok ? "✅" : c.required ? "❌" : "⚠️";
    console.log(`  ${mark} ${c.name.padEnd(22)} ${c.detail}`);
  }
  const voice = !!config.elevenlabs.apiKey;
  const pexels = !!config.pexels.apiKey;
  const llm = hasLlmKey();
  if (voice && pexels) {
    console.log(
      llm
        ? "  → Real demo Short: Claude script + ElevenLabs voice + Pexels B-roll. No YouTube OAuth."
        : "  → Real demo Short: canned script + ElevenLabs voice + Pexels B-roll. Set ANTHROPIC_API_KEY for a fresh script.",
    );
  } else if (voice || pexels) {
    console.log(
      "  → Partial demo will run (stubs for the missing piece). For a voiced stock Short set both ELEVENLABS_API_KEY and PEXELS_API_KEY.",
    );
  } else {
    console.log(
      "  → Offline fallback will run (silent audio + title cards). Minimum for a real first video: ANTHROPIC_API_KEY + ELEVENLABS_API_KEY + PEXELS_API_KEY. YouTube OAuth is not required for --demo.",
    );
  }
  console.log("");
}

function demoFailure(reason: string, checks: DemoCheck[]): string {
  const lines = [
    reason,
    "",
    "Demo vs full run:",
    "  --demo first video:  ffmpeg + ANTHROPIC_API_KEY (or canned script) + ELEVENLABS_API_KEY + PEXELS_API_KEY",
    "  --demo does NOT need YouTube OAuth, YOUTUBE_CLIENT_ID, or YOUTUBE_CLIENT_SECRET",
    "  missing TTS/visuals: silent stub audio / generated title cards (valid 1080×1920, not a voiced stock Short)",
    "  full upload path:    the demo keys PLUS YOUTUBE_CLIENT_ID/SECRET and `npm run auth`",
    "",
    "Current checks:",
    ...checks.map((c) => `  ${c.ok ? "ok" : "missing"}  ${c.name} — ${c.detail}`),
    "",
    "Copy .env.example to .env, fill the demo keys, then: npm run make -- --demo",
    "Run `npm run doctor` to see demo vs full-run readiness.",
  ];
  return lines.join("\n");
}

/**
 * Silent audio + estimated word timings so captions still burn when ElevenLabs
 * is unset. Not a substitute for a real voice — logged as a stub.
 */
export async function stubTts(text: string, audioPath: string): Promise<TtsResult> {
  log("demo", "no ELEVENLABS_API_KEY — silent stub audio (captions still burn)");
  const tokens = text.split(/\s+/).filter(Boolean);
  const per = 0.42;
  const words: Word[] = tokens.map((t, i) => ({
    text: t,
    start: i * per,
    end: (i + 1) * per,
  }));
  const dur = Math.max(words.at(-1)?.end ?? 2, 2);
  await run("ffmpeg", [
    "-y",
    "-f",
    "lavfi",
    "-i",
    "anullsrc=r=44100:cl=mono",
    "-t",
    String(dur),
    "-c:a",
    "libmp3lame",
    "-q:a",
    "4",
    audioPath,
  ]);
  return { audioPath, words };
}

/**
 * 1080×1920 title cards (canvas + Ken Burns) when Pexels is unset. No stock
 * binaries shipped — generated at runtime.
 */
export async function stubVisuals(
  queries: string[],
  dir: string,
  clipSeconds: number,
): Promise<string[]> {
  log("demo", "no PEXELS_API_KEY — generating title-card clips (not stock footage)");
  const q = queries.length ? queries : ["demo"];
  const paths: string[] = [];
  for (let i = 0; i < q.length; i++) {
    const img = path.join(dir, `demo-card-${String(i).padStart(2, "0")}.png`);
    await drawTitleCard(q[i], i, img);
    const clip = path.join(dir, `demo-clip-${String(i).padStart(2, "0")}.mp4`);
    // Hold the card still — Ken Burns on big type crops the query off-frame.
    const { width, height, fps } = config.video;
    await run("ffmpeg", [
      "-y",
      "-loop",
      "1",
      "-i",
      img,
      "-t",
      String(clipSeconds),
      "-vf",
      `scale=${width}:${height}:force_original_aspect_ratio=increase,crop=${width}:${height},fps=${fps},setsar=1`,
      "-c:v",
      "libx264",
      "-pix_fmt",
      "yuv420p",
      clip,
    ]);
    paths.push(clip);
  }
  return paths;
}

async function drawTitleCard(query: string, index: number, outPath: string): Promise<void> {
  const { width, height } = config.video;
  const canvas = createCanvas(width, height);
  const ctx = canvas.getContext("2d");
  const hues = [210, 160, 25, 280];
  const h = hues[index % hues.length];
  const g = ctx.createLinearGradient(0, 0, 0, height);
  g.addColorStop(0, `hsl(${h}, 45%, 14%)`);
  g.addColorStop(1, `hsl(${h}, 40%, 6%)`);
  ctx.fillStyle = g;
  ctx.fillRect(0, 0, width, height);

  ctx.fillStyle = "rgba(255,230,0,0.9)";
  ctx.fillRect(64, 220, 120, 10);

  ctx.fillStyle = "#FFFFFF";
  ctx.textAlign = "left";
  ctx.textBaseline = "top";
  const words = query.toUpperCase().split(/\s+/);
  let font = 72;
  ctx.font = `800 ${font}px sans-serif`;
  const maxW = width - 128;
  const lines: string[] = [];
  let line = "";
  for (const w of words) {
    const next = line ? `${line} ${w}` : w;
    if (ctx.measureText(next).width > maxW && line) {
      lines.push(line);
      line = w;
    } else line = next;
  }
  if (line) lines.push(line);
  while (lines.some((l) => ctx.measureText(l).width > maxW) && font > 40) {
    font -= 4;
    ctx.font = `800 ${font}px sans-serif`;
  }
  lines.forEach((l, i) => ctx.fillText(l, 64, 260 + i * (font + 18)));

  ctx.font = "600 28px sans-serif";
  ctx.fillStyle = "rgba(255,255,255,0.45)";
  ctx.fillText("shorts-rev demo · title card (no Pexels key)", 64, height - 120);

  await writeFile(outPath, canvas.toBuffer("image/png"));
}
